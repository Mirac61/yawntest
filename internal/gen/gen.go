package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"
	"text/template"

	"github.com/Mirac61/lazytest/internal/detect"
)

type Test struct {
	Match   detect.Match
	Summary string // e.g. "1 test" or "fuzz, 8 seeds"
}

type Output struct {
	Code    []byte // nil if no test was generated
	Tests   []Test
	Skipped []detect.Match // needs inputs lazytest can't build, e.g. constructor dependencies
}

func TestPath(sourcePath string) string {
	return strings.TrimSuffix(sourcePath, ".go") + "_lazytest_test.go"
}

func File(pkg string, matches []detect.Match) (Output, error) {
	b := &builder{imports: map[string]bool{}}

	var out Output
	for _, match := range matches {
		summary, ok := b.add(match)
		if !ok {
			out.Skipped = append(out.Skipped, match)
			continue
		}
		out.Tests = append(out.Tests, Test{Match: match, Summary: summary})
	}
	if len(out.Tests) == 0 {
		return out, nil
	}

	code, err := b.render(pkg)
	if err != nil {
		return Output{}, err
	}
	out.Code = code
	return out, nil
}

type builder struct {
	imports map[string]bool
	body    bytes.Buffer
	err     error // first template error, reported by render
}

func (b *builder) add(match detect.Match) (summary string, ok bool) {
	switch match.Pattern {
	case detect.PatternJSONRoundtrip:
		return b.roundtrip(match), true
	case detect.PatternPureFunc:
		return b.fuzz(match), true
	case detect.PatternHTTPHandler:
		return b.httpHandler(match)
	case detect.PatternValidation:
		return b.validation(match)
	default:
		return "", false
	}
}

// callable returns how a test calls the func: Add, or new(Server).CreateTask for methods.
func callable(name string) string {
	receiver, method, isMethod := strings.Cut(name, ".")
	if !isMethod {
		return name
	}
	return "new(" + receiver + ")." + method
}

func testName(name string) string {
	return strings.ReplaceAll(name, ".", "_")
}

func (b *builder) use(imports ...string) {
	for _, path := range imports {
		b.imports[path] = true
	}
}

func (b *builder) execute(tmpl *template.Template, data any) {
	if b.err != nil {
		return
	}
	b.err = tmpl.Execute(&b.body, data)
}

var fileTemplate = template.Must(template.New("file").Parse(`// Code generated by lazytest. Edit freely; rerun with --force to regenerate.

package {{.Package}}

import (
{{range .Imports}}	"{{.}}"
{{end}})
{{.Body}}`))

// noPanic is pasted into every test: one panic then fails only its own test and the
// rest of the package still runs. A shared helper func would clash between lazytest files.
func noPanic(note string) string {
	report := `t.Errorf("panic: %v", r)`
	if note != "" {
		report = `t.Errorf("panic: %v (` + note + `)", r)`
	}
	return "defer func() {\n\tif r := recover(); r != nil {\n\t\t" + report + "\n\t}\n}()"
}

// zeroReceiverNote explains panics of methods, which run on a zero-valued receiver.
func zeroReceiverNote(name string) string {
	receiver, _, isMethod := strings.Cut(name, ".")
	if !isMethod {
		return ""
	}
	return "the " + receiver + " is zero-valued; give it real dependencies if it needs them"
}

func (b *builder) render(pkg string) ([]byte, error) {
	if b.err != nil {
		return nil, fmt.Errorf("render test: %w", b.err)
	}

	var source bytes.Buffer
	err := fileTemplate.Execute(&source, map[string]any{
		"Package": pkg,
		"Imports": slices.Sorted(maps.Keys(b.imports)),
		"Body":    b.body.String(),
	})
	if err != nil {
		return nil, fmt.Errorf("render file: %w", err)
	}

	code, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return code, nil
}
